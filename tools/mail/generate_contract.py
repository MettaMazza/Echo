#!/usr/bin/env python3
"""Generate native Gmail wire metadata from Google's pinned discovery document."""
import argparse
import hashlib
import json
from pathlib import Path

PIN = 'f786812d1816c2e2c54dfe2d739dd6e8c28aa3dfe6af627ab7827294fa0d40a2'

def generate(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != PIN:
        raise ValueError('Gmail discovery digest mismatch; review upstream changes before repinning')
    document = json.loads(raw)
    if document['rootUrl'] != 'https://gmail.googleapis.com/' or document['id'] != 'gmail:v1':
        raise ValueError('Unexpected API identity')
    methods = {}
    def visit(resource):
        for method in resource.get('methods', {}).values():
            name = method['id'].removeprefix('gmail.users.')
            # Local polling requires no Pub/Sub account or inbound endpoint.
            if name in ('watch', 'stop') or '.cse.' in name:
                continue
            scopes = [s for s in method.get('scopes', []) if '/gmail.addons.' not in s]
            methods[name] = {
                'method': method['httpMethod'], 'path': method['path'],
                'parameters': {k: {a: v for a, v in p.items() if a in (
                    'location', 'type', 'required', 'repeated', 'enum', 'format', 'minimum', 'maximum')}
                    for k, p in method.get('parameters', {}).items() if k != 'userId'},
                'scopes': scopes,
                'request': method.get('request', {}).get('$ref', ''),
                'sharing_scope_only': bool(scopes) and all(s.endswith('/gmail.settings.sharing') for s in scopes),
                'effect': ('read' if method['httpMethod'] == 'GET' else
                           'send' if name in ('messages.send', 'drafts.send') else
                           'permanent-delete' if name in ('messages.delete', 'messages.batchDelete', 'threads.delete', 'drafts.delete') else 'write'),
            }
        for child in resource.get('resources', {}).values():
            visit(child)
    visit(document['resources']['users'])
    lines = [f'# Generated by tools/mail/generate_contract.py; Gmail revision {document["revision"]}.',
             f'# Discovery SHA-256 {PIN}; no runtime discovery or user-provided endpoints.',
             'define gmail_method_contract with operation as Str returning Str:']
    for name, method in sorted(methods.items()):
        lines += [f'    if operation equals {json.dumps(name)}:',
                  '        return ' + json.dumps(json.dumps(method, separators=(',', ':'), sort_keys=True))]
    lines += ['    return ""', '']
    return '\n'.join(lines)

def generate_payload_schemas(source):
    # Reuse the same pinned upstream identity check before extracting types.
    generate(source)
    document = json.loads(source.read_bytes())
    references = set()
    def visit(resource):
        for method in resource.get('methods', {}).values():
            if method['id'] not in ('gmail.users.watch', 'gmail.users.stop') and '.cse.' not in method['id']:
                if 'request' in method:
                    references.add(method['request']['$ref'])
        for child in resource.get('resources', {}).values():
            visit(child)
    visit(document['resources']['users'])
    def prune(node):
        result = {}
        for key in ('type', '$ref', 'format', 'enum', 'annotations'):
            if key in node:
                result[key] = node[key]
        if '$ref' in node:
            references.add(node['$ref'])
        if 'properties' in node:
            result['properties'] = {k: prune(v) for k, v in node['properties'].items()}
        if 'items' in node:
            result['items'] = prune(node['items'])
        return result
    schemas = {}
    while references - schemas.keys():
        name = sorted(references - schemas.keys())[0]
        schemas[name] = prune(document['schemas'][name])
    lines = [f'# Generated from Gmail discovery SHA-256 {PIN}.',
             '# Structural request types and operation-specific required annotations.',
             'define gmail_payload_schema with name as Str returning Str:']
    for name, schema in sorted(schemas.items()):
        lines += [f'    if name equals {json.dumps(name)}:',
                  '        return ' + json.dumps(json.dumps(schema, sort_keys=True, separators=(',', ':')))]
    return '\n'.join(lines + ['    return ""', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('discovery', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--payload-schemas', type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.discovery))
    if args.payload_schemas:
        args.payload_schemas.write_text(generate_payload_schemas(args.discovery))
